# ---------- 检索 ----------

_TOKEN_DICT: set[str] = set()
for _e in APPEAL_CATALOG.values():
    _TOKEN_DICT.update(_e.get("keywords", []))


def _tokenize(query: str) -> list[str]:
    """简易中文分词: 标点拆分 + 词典最大逆向匹配（贪心 6 字→1 字）。"""
    if not query:
        return []
    parts = re.split(r"[\s,，。、；;：:？?！!·\-_/\\（）()【】\[\]\"'“”‘’]+", query)
    tokens: list[str] = []
    for part in parts:
        if not part:
            continue
        i, n = 0, len(part)
        while i < n:
            matched = None
            for size in range(min(6, n - i), 1, -1):
                piece = part[i:i + size]
                if piece in _TOKEN_DICT:
                    matched = piece
                    break
            if matched:
                tokens.append(matched)
                i += len(matched)
            else:
                i += 1
    return tokens


def get_appeal_topic(code: str) -> dict[str, Any] | None:
    """按 code 精确取主题（大小写不敏感兜底）。"""
    if not code:
        return None
    entry = APPEAL_CATALOG.get(code)
    if entry:
        return {"code": code, **entry}
    for k, v in APPEAL_CATALOG.items():
        if k.lower() == str(code).lower():
            return {"code": k, **v}
    return None


def search_appeal_topics(query: str, top_k: int = 3) -> list[dict[str, Any]]:
    """按自然语言问题检索相关主题，按命中分降序。"""
    tokens = _tokenize(query)
    token_set = set(tokens)
    scored: list[tuple[float, dict[str, Any]]] = []
    for code, e in APPEAL_CATALOG.items():
        haystack = set(e.get("keywords", []))
        hits = token_set & haystack
        score = float(len(hits))
        # title/summary 命中加权（低权重）
        score += 0.25 * sum(1 for tok in tokens if tok in e.get("title", ""))
        score += 0.1 * sum(1 for tok in tokens if tok in e.get("summary", ""))
        if score <= 0:
            continue
        scored.append((score, {"code": code, **e, "score": round(score, 2)}))
    scored.sort(key=lambda x: (-x[0], x[1]["code"]))
    return [t[1] for t in scored[:top_k]]


def list_topics_brief() -> list[dict[str, Any]]:
    """主题简要清单（列表端点用）。"""
    return [{"code": c, "category": e["category"], "title": e["title"],
             "summary": e["summary"]} for c, e in APPEAL_CATALOG.items()]


def format_appeal_text(entry: dict[str, Any]) -> str:
    """把结构化主题渲染为问答友好文本（供 Agent 工具返回）。"""
    lines = [
        f"【主题】{entry.get('title')}（{entry.get('category')}，code={entry.get('code')}）",
        f"【问题概述】{entry.get('summary', '')}",
        f"【提出渠道】{entry.get('channel', '')}",
        f"【法定时限】{entry.get('deadline', '')}",
        "【所需材料】",
    ]
    for m in entry.get("materials", []):
        lines.append(f"  · {m}")
    lines.append("【操作步骤】")
    for i, s in enumerate(entry.get("steps", []), 1):
        lines.append(f"  {i}. {s}")
    lines.append(f"【法规依据】{entry.get('legal_basis', '')}")
    notes = entry.get("notes")
    if notes:
        lines.append(f"【注意事项】{notes}")
    return "\n".join(lines)
