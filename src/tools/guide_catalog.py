# ---------- 索引与识别 ----------

_WORKFLOW_INDEX: dict[str, dict[str, Any]] = {w["id"]: w for w in GUIDE_WORKFLOWS}

_TOKEN_DICT: set[str] = set()
for _w in GUIDE_WORKFLOWS:
    _TOKEN_DICT.update(_w.get("keywords", []))
    for _s in _w["stages"]:
        _TOKEN_DICT.update(_s.get("keywords", []))


def _tokenize(query: str) -> list[str]:
    """标点拆分 + 词典最大逆向匹配（贪心 6 字→2 字）。"""
    if not query:
        return []
    parts = re.split(r"[\s,，。、；;：:？?！!·\-_/\\（）()【】\[\]\"'“”‘’]+", query)
    tokens: list[str] = []
    for part in parts:
        if not part:
            continue
        i, n = 0, len(part)
        while i < n:
            matched = None
            for size in range(min(6, n - i), 1, -1):
                piece = part[i:i + size]
                if piece in _TOKEN_DICT:
                    matched = piece
                    break
            if matched:
                tokens.append(matched)
                i += len(matched)
            else:
                i += 1
    return tokens


def get_workflow(wid: str) -> dict[str, Any] | None:
    return _WORKFLOW_INDEX.get(wid)


def list_workflows_brief() -> list[dict[str, Any]]:
    return [{"id": w["id"], "role": w["role"], "name": w["name"],
             "summary": w["summary"], "stage_count": len(w["stages"])}
            for w in GUIDE_WORKFLOWS]


def recognize_stage(query: str) -> dict[str, Any] | None:
    """识别用户当前所处的流程与阶段。

    返回 {workflow, stage_index, stage, prev_stage, next_stage, score}；
    仅命中流程未命中具体阶段时 stage_index=0 并标注 stage_locked=False。
    """
    tokens = set(_tokenize(query))
    if not tokens:
        return None
    best: tuple[float, int, dict[str, Any]] | None = None  # (stage_score, idx, workflow)
    for w in GUIDE_WORKFLOWS:
        wf_hits = tokens & set(w.get("keywords", []))
        for idx, st in enumerate(w["stages"]):
            stage_hits = tokens & set(st.get("keywords", []))
            # 必须命中至少 1 个阶段专属关键词才锁定阶段（流程级命中仅作加权）
            if not stage_hits:
                continue
            score = float(len(stage_hits)) + 0.3 * len(wf_hits)
            if best is None or score > best[0]:
                best = (score, idx, w)
    if best is None:
        # 只命中流程级关键词
        wf_best: tuple[float, dict[str, Any]] | None = None
        for w in GUIDE_WORKFLOWS:
            s = float(len(tokens & set(w.get("keywords", []))))
            if s > 0 and (wf_best is None or s > wf_best[0]):
                wf_best = (s, w)
        if wf_best is None:
            return None
        w = wf_best[1]
        idx = 0
        stage_locked = False
        score = wf_best[0]
    else:
        score, idx, w = best
        stage_locked = True

    stages = w["stages"]
    return {
        "score": round(score, 2),
        "stage_locked": stage_locked,
        "workflow": {"id": w["id"], "role": w["role"], "name": w["name"],
                     "summary": w["summary"]},
        "stage_index": idx,
        "stage": stages[idx],
        "prev_stage": stages[idx - 1]["name"] if idx > 0 else None,
        "next_stage": stages[idx + 1]["name"] if idx + 1 < len(stages) else None,
    }


def format_guide_text(rec: dict[str, Any]) -> str:
    """把识别结果渲染为问答友好文本（供 Agent 工具返回）。"""
    w, st = rec["workflow"], rec["stage"]
    pos = rec["stage_index"] + 1
    total = len(_WORKFLOW_INDEX[w["id"]]["stages"])
    lines = [
        f"【识别结果】{w['name']}（id={w['id']}，适用角色：{w['role']}）— 当前阶段：{st['name']}（第 {pos}/{total} 步）",
        f"【本阶段目标】{st['purpose']}",
    ]
    if not rec.get("stage_locked", True):
        lines.append("（未精确定位到具体操作阶段，默认从第一步开始；如非该阶段请补充描述，例如\"上传投标文件失败\"\"开标怎么解密\"）")
    if rec.get("prev_stage"):
        lines.append(f"【上一阶段】{rec['prev_stage']}")
    lines.append("【前置条件/材料】")
    for p in st.get("prerequisites", []):
        lines.append(f"  · {p}")
    lines.append("【操作步骤】")
    for i, a in enumerate(st.get("actions", []), 1):
        lines.append(f"  {i}. {a}")
    ces = st.get("common_errors", [])
    if ces:
        lines.append("【常见错误/坑】")
        for e in ces:
            lines.append(f"  ⚠ {e}")
    tip = st.get("tips")
    if tip:
        lines.append(f"【提示】{tip}")
    if rec.get("next_stage"):
        lines.append(f"【下一阶段】{rec['next_stage']}")
    return "\n".join(lines)
