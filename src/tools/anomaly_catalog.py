def get_anomaly_guidance(code: str) -> dict[str, Any] | None:
    """按 code 取结构化解释。返回 None 表示该 code 暂无人工编写的解释。"""
    if not code:
        return None
    entry = ANOMALY_CATALOG.get(code)
    if entry:
        return {"code": code, **entry}
    # 模糊兜底: code 大小写不敏感
    for k, v in ANOMALY_CATALOG.items():
        if k.lower() == str(code).lower():
            return {"code": k, **v}
    return None


def list_all_codes() -> list[str]:
    return list(ANOMALY_CATALOG.keys())


def format_guidance_text(entry: dict[str, Any]) -> str:
    """把结构化解释渲染成问答友好的纯文本（供 Agent 工具返回）。"""
    lines = [
        f"【异常项】{entry.get('item', '-')}（code={entry.get('code')}，级别={entry.get('level')}）",
        f"【问题说明】{entry.get('summary', '')}",
        f"【可能原因】",
    ]
    for c in entry.get("causes", []):
        lines.append(f"  - {c}")
    lines.append(f"【影响】{entry.get('impact', '')}")
    lines.append("【处置建议】")
    for a in entry.get("actions", []):
        lines.append(f"  {a if a[0].isdigit() else '· ' + a}")
    lb = entry.get("legal_basis")
    if lb:
        lines.append(f"【法规依据】{lb}")
    return "\n".join(lines)
