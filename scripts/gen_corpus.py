# ── 企业线 Q&A (从 ccgp_structured.xlsx 生成) ──────────────
def generate_enterprise_qa():
    """从 ccgp_structured.xlsx 生成企业线 Q&A."""
    import openpyxl
    wb = openpyxl.load_workbook(ROOT / "data" / "raw" / "ccgp_structured.xlsx", read_only=True)
    ws = wb.active
    headers = [c.value for c in next(ws.iter_rows(min_row=1, max_row=1))]
    qa_list = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        proj = dict(zip(headers, row))
        pname = (proj.get("project_name") or "").strip()
        if not pname:
            continue
        buyer = (proj.get("buyer") or "").strip()
        agent = (proj.get("agent") or "").strip()
        budget = (proj.get("budget") or "").strip()
        bid_time = (proj.get("bid_time") or "").strip()
        bid_place = (proj.get("bid_place") or "").strip()
        method = (proj.get("purchase_method") or "").strip()
        code = (proj.get("project_code") or "").strip()
        region = (proj.get("admin_region") or "").strip()

        if buyer:
            qa_list.append((f"{pname}的采购单位是谁？",
                f"{pname}的采购单位是{buyer}。",
                "ccgp_structured", "采购单位", "enterprise"))
        if agent:
            qa_list.append((f"{pname}的代理机构是什么？",
                f"{pname}的代理机构是{agent}。",
                "ccgp_structured", "代理机构", "enterprise"))
        if budget:
            qa_list.append((f"{pname}的预算金额是多少？",
                f"{pname}的预算金额为{budget}。",
                "ccgp_structured", "预算金额", "enterprise"))
        if bid_time:
            qa_list.append((f"{pname}的开标时间是什么时候？",
                f"{pname}的开标时间为{bid_time}。",
                "ccgp_structured", "开标时间", "enterprise"))
        if bid_place:
            qa_list.append((f"{pname}的开标地点在哪里？",
                f"{pname}的开标地点为{bid_place}。",
                "ccgp_structured", "开标地点", "enterprise"))
        if method:
            qa_list.append((f"{pname}的采购方式是什么？",
                f"{pname}的采购方式为{method}。",
                "ccgp_structured", "采购方式", "enterprise"))
        if code:
            qa_list.append((f"{pname}的项目编号是什么？",
                f"{pname}的项目编号为{code}。",
                "ccgp_structured", "项目编号", "enterprise"))
        if region:
            qa_list.append((f"{pname}的行政区域是哪里？",
                f"{pname}的行政区域为{region}。",
                "ccgp_structured", "行政区域", "enterprise"))
    wb.close()
    return qa_list


def write_excel(qa_list, path, extra_col="business_line"):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sheet1"
    headers = ["question", "answer", "source_file", "section_title", "doc_type", extra_col]
    ws.append(headers)
    for row in qa_list:
        ws.append(list(row))
    wb.save(path)
    wb.close()
    print(f"  -> {path}: {len(qa_list)} rows")


def main():
    # 1. 法规线
    print("[1/2] 生成法规线 Q&A ...")
    reg_path = ROOT / "data" / "raw" / "regulation_qa.xlsx"
    write_excel(REGULATION_QA, reg_path)

    # 2. 企业线
    print("[2/2] 生成企业线 Q&A ...")
    ent_path = ROOT / "data" / "raw" / "enterprise_qa.xlsx"
    ent_qa = generate_enterprise_qa()
    write_excel(ent_qa, ent_path)

    print(f"\n总计: 法规线 {len(REGULATION_QA)} 条 + 企业线 {len(ent_qa)} 条")
    print(f"原有招标线 75 条 (ccgp_qa.xlsx)")
    print(f"合计: {len(REGULATION_QA) + len(ent_qa) + 75} 条")


if __name__ == "__main__":
    main()
